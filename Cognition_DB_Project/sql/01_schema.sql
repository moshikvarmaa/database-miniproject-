-- Cognition Learner Intelligence Database System
-- Oracle SQL schema. Run as your project schema/user in SQL Developer or SQL*Plus.

CREATE TABLE learner (
    learner_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    participant_code VARCHAR2(30) NOT NULL UNIQUE,
    display_name     VARCHAR2(80),
    created_at       TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    active_flag      CHAR(1) DEFAULT 'Y' NOT NULL CHECK (active_flag IN ('Y','N'))
);

CREATE TABLE topic (
    topic_id     NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    topic_name   VARCHAR2(100) NOT NULL UNIQUE,
    description  VARCHAR2(500)
);

CREATE TABLE learning_session (
    session_id   NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    learner_id   NUMBER NOT NULL,
    topic_id     NUMBER NOT NULL,
    started_at   TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    ended_at     TIMESTAMP,
    status       VARCHAR2(20) DEFAULT 'OPEN' NOT NULL
                 CHECK (status IN ('OPEN','COMPLETED','CANCELLED')),
    CONSTRAINT fk_session_learner FOREIGN KEY (learner_id)
        REFERENCES learner(learner_id),
    CONSTRAINT fk_session_topic FOREIGN KEY (topic_id)
        REFERENCES topic(topic_id),
    CONSTRAINT ck_session_times CHECK (ended_at IS NULL OR ended_at >= started_at)
);

CREATE TABLE interaction (
    interaction_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id     NUMBER NOT NULL,
    event_time     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    speaker        VARCHAR2(10) NOT NULL CHECK (speaker IN ('LEARNER','TUTOR')),
    message_text   CLOB NOT NULL,
    event_type     VARCHAR2(30) DEFAULT 'GENERAL' NOT NULL
                   CHECK (event_type IN ('GENERAL','CONFUSION','CLARIFICATION',
                                         'EXAMPLE_SEEKING','CONCEPT_REVISIT','SUCCESS')),
    concept_name   VARCHAR2(120),
    CONSTRAINT fk_interaction_session FOREIGN KEY (session_id)
        REFERENCES learning_session(session_id) ON DELETE CASCADE
);

CREATE TABLE signal (
    signal_id       NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    interaction_id  NUMBER NOT NULL,
    signal_type     VARCHAR2(30) NOT NULL
                    CHECK (signal_type IN ('CONFUSION','CLARIFICATION',
                                           'EXAMPLE_SEEKING','CONCEPT_REVISIT','SUCCESS')),
    confidence      NUMBER(4,3) CHECK (confidence BETWEEN 0 AND 1),
    review_status   VARCHAR2(15) DEFAULT 'UNREVIEWED' NOT NULL
                    CHECK (review_status IN ('UNREVIEWED','ACCEPTED','REJECTED')),
    CONSTRAINT fk_signal_interaction FOREIGN KEY (interaction_id)
        REFERENCES interaction(interaction_id) ON DELETE CASCADE
);

CREATE TABLE state_transition (
    transition_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id    NUMBER NOT NULL,
    from_state    VARCHAR2(30),
    to_state      VARCHAR2(30) NOT NULL
                  CHECK (to_state IN ('START','LEARNING','CLARIFICATION_NEEDED',
                                      'NEEDS_PRACTICE','IMPROVING','MASTERED')),
    event_time    TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    reason        VARCHAR2(500),
    CONSTRAINT fk_transition_session FOREIGN KEY (session_id)
        REFERENCES learning_session(session_id) ON DELETE CASCADE
);

CREATE TABLE concept_progress (
    progress_id    NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    learner_id     NUMBER NOT NULL,
    topic_id       NUMBER NOT NULL,
    concept_name   VARCHAR2(120) NOT NULL,
    status         VARCHAR2(20) DEFAULT 'LEARNING' NOT NULL
                   CHECK (status IN ('NOT_STARTED','LEARNING','NEEDS_PRACTICE',
                                     'IMPROVING','MASTERED')),
    mastery_score  NUMBER(5,2) DEFAULT 0 NOT NULL CHECK (mastery_score BETWEEN 0 AND 100),
    updated_at     TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
    CONSTRAINT fk_progress_learner FOREIGN KEY (learner_id)
        REFERENCES learner(learner_id),
    CONSTRAINT fk_progress_topic FOREIGN KEY (topic_id)
        REFERENCES topic(topic_id),
    CONSTRAINT uq_progress UNIQUE (learner_id, topic_id, concept_name)
);

CREATE INDEX idx_session_learner ON learning_session(learner_id);
CREATE INDEX idx_interaction_session ON interaction(session_id);
CREATE INDEX idx_interaction_type ON interaction(event_type);
CREATE INDEX idx_progress_learner ON concept_progress(learner_id);

